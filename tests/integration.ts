import assert from "node:assert/strict";
import { randomUUID, randomBytes, createHash } from "crypto";
import { PrismaClient } from "@prisma/client";
import { changeOrderStatus } from "../lib/order-status";
import { reserveCheckout } from "../lib/checkout-order";
import { receiptTokenFor } from "../lib/payment-checkout";
import { confirmPayment, processPaymentEvent, releaseReservation } from "../lib/payment-state";
import { parseBakeryDateTime } from "../lib/bakery-time";
import { processEmailQueue } from "../lib/email-queue";
const databaseUrl = process.env.DATABASE_URL || "";
if (!new URL(databaseUrl).pathname.endsWith("/kneaded_loaves_test")) throw new Error("Integration tests require the dedicated kneaded_loaves_test database.");
const prisma = new PrismaClient();
const base = process.env.TEST_APP_URL || "http://127.0.0.1:3001";
async function request(path: string, body?: unknown, cookie?: string, method = "POST") {
  return fetch(base + path, { method, redirect: "manual", headers: { "Content-Type": "application/json", Origin: base, ...(cookie ? { Cookie: cookie } : {}) }, ...(body !== undefined ? { body: JSON.stringify(body) } : {}) });
}
async function main() {
  process.env.CONFIG_ENCRYPTION_KEY = randomBytes(32).toString("hex");
  process.env.TAX_RATE_BPS = "0"; process.env.TAX_DELIVERY_FEE = "false";
  // Only this dedicated test database is reset. Never point these tests at shop data.
  await prisma.paymentEvent.deleteMany(); await prisma.orderItem.deleteMany(); await prisma.order.deleteMany(); await prisma.cartItem.deleteMany(); await prisma.cart.deleteMany();
  await prisma.product.deleteMany(); await prisma.orderWindow.deleteMany(); await prisma.emailJob.deleteMany(); await prisma.rateLimit.deleteMany();
  const suffix = randomUUID();
  const product = await prisma.product.create({ data: { name: "Test loaf", slug: suffix, description: "Integration test loaf", priceCents: 1000, inventoryLimit: 10, allergens: [], ingredients: [] } });
  const pickup = await prisma.pickupLocation.create({ data: { name: "Test pickup", address: "Test address", instructions: "Test pickup instructions" } });
  const saturday = new Date(Date.now() + 14 * 86400000);
  while (saturday.getUTCDay() !== 6) saturday.setUTCDate(saturday.getUTCDate() + 1);
  const thursday = new Date(saturday.getTime() - 2 * 86400000);
  const dateString = (date: Date) => date.toISOString().slice(0, 10);
  const window = await prisma.orderWindow.create({ data: { name: "Test window", opensAt: new Date(Date.now() - 60000), closesAt: parseBakeryDateTime(`${dateString(thursday)}T18:00`), fulfillmentDate: parseBakeryDateTime(`${dateString(saturday)}T10:00`), maxOrders: 1 } });
  const payload = { customerName: "Test Customer", customerEmail: "test@example.invalid", fulfillmentType: "PICKUP" as const, pickupLocationId: pickup.id, orderWindowId: window.id, paymentProvider: "STRIPE" as const, checkoutKey: randomUUID() };
  const carts = await Promise.all([0, 1].map(async () => {
    const result = await request("/api/cart", { productId: product.id, quantity: 1 });
    assert.equal(result.status, 200, await result.clone().text());
    const cookie = result.headers.get("set-cookie")!.split(";")[0];
    const cart = await prisma.cart.findUniqueOrThrow({ where: { sessionId: cookie.split("=")[1] } });
    return { cookie, id: cart.id };
  }));
  assert.notEqual(carts[0].id, carts[1].id);
  // Without real provider readiness, the public endpoint fails closed before stock changes.
  assert.equal((await request("/api/checkout", payload, carts[0].cookie)).status, 503);
  assert.equal(await prisma.order.count(), 0);
  assert.equal(await prisma.cartItem.count(), 2);
  for (const quantity of [-1, 0.5, "2", 1001]) assert.equal((await request("/api/cart", { productId: product.id, quantity }, carts[0].cookie)).status, 400);
  const crossSite = await fetch(base + "/api/cart", { method: "POST", headers: { Origin: "https://untrusted.example", "Content-Type": "application/json" }, body: JSON.stringify({ productId: product.id, quantity: 1 }) });
  assert.equal(crossSite.status, 403);
  console.log("PASS: launch gate, invalid quantities and cross-origin mutations rejected");
  const attempts = carts.map(cart => ({ cart, data: { ...payload, checkoutKey: randomUUID() } }));
  const checkout = await Promise.allSettled(attempts.map(({ cart, data }) => reserveCheckout(data, cart.id)));
  assert.equal(checkout.filter(result => result.status === "fulfilled").length, 1);
  const winner = checkout.findIndex(result => result.status === "fulfilled");
  const orderId = (checkout[winner] as PromiseFulfilledResult<string>).value;
  assert.equal(await reserveCheckout(attempts[winner].data, attempts[winner].cart.id), orderId);
  assert.equal(await prisma.order.count(), 1);
  assert.equal((await prisma.product.findUniqueOrThrow({ where: { id: product.id } })).inventoryLimit, 9);
  assert.equal(await prisma.emailJob.count(), 0);
  assert.equal(await prisma.cartItem.count(), 2);
  console.log("PASS: concurrent checkout and retries respect capacity, stock and saved carts");
  const token = await receiptTokenFor(orderId);
  assert.equal((await fetch(base + `/orders/${orderId}`, { redirect: "manual" })).status, 404);
  assert.equal((await fetch(base + `/orders/${orderId}?receipt=${token}`)).status, 200);
  const proof = { orderId, provider: "STRIPE" as const, providerOrderId: "cs_integration", paymentId: "pi_integration", amountCents: 1000, currency: "usd" };
  await assert.rejects(prisma.$transaction(tx => confirmPayment(tx, { ...proof, amountCents: 1 })));
  assert.equal((await prisma.order.findUniqueOrThrow({ where: { id: orderId } })).paymentState, "PENDING");
  await Promise.all([0, 1].map(() => processPaymentEvent("STRIPE", "evt_integration", "checkout.session.completed", orderId, tx => confirmPayment(tx, proof))));
  assert.equal(await prisma.paymentEvent.count(), 1);
  assert.equal(await prisma.emailJob.count(), 1);
  assert.equal(await prisma.cartItem.count(), 1);
  assert.equal((await prisma.order.findUniqueOrThrow({ where: { id: orderId } })).paymentState, "PAID");
  await prisma.$transaction(tx => releaseReservation(tx, orderId, "EXPIRED"));
  assert.equal((await prisma.product.findUniqueOrThrow({ where: { id: product.id } })).inventoryLimit, 9);
  await assert.rejects(prisma.$transaction(tx => changeOrderStatus(tx, orderId, "CANCELLED")));
  console.log("PASS: exact payment matching, concurrent event idempotency, paid-email queue and no late restock");
  await prisma.orderWindow.update({ where: { id: window.id }, data: { maxOrders: 2 } });
  const loser = attempts[1 - winner];
  const abandoned = await reserveCheckout({ ...loser.data, paymentProvider: "PAYPAL" }, loser.cart.id);
  await Promise.all([0, 1].map(() => prisma.$transaction(tx => releaseReservation(tx, abandoned, "EXPIRED"))));
  assert.equal((await prisma.product.findUniqueOrThrow({ where: { id: product.id } })).inventoryLimit, 9);
  console.log("PASS: abandoned reservation restores stock exactly once");
  const email = `customer-${suffix}@example.invalid`, password = "Local-test-password-2026";
  assert.equal((await request("/api/auth/register", { name: "Test Customer", email, password })).status, 200);
  const login = await fetch(base + "/api/auth/login", { method: "POST", redirect: "manual", headers: { Origin: base }, body: new URLSearchParams({ email, password }) });
  assert.equal(login.status, 303); assert.equal(new URL(login.headers.get("location")!).pathname, "/account");
  const cookie = login.headers.get("set-cookie")!.split(";")[0];
  assert.equal((await request("/api/admin/setup", { values: [] }, cookie)).status, 307);
  assert.equal((await request("/api/auth/change-password", { currentPassword: password, password: "Another-test-password-2026" }, cookie)).status, 200);
  assert.equal((await request("/api/auth/change-password", { currentPassword: "Another-test-password-2026", password }, cookie)).status, 401);
  console.log("PASS: registration, login, admin authorization and session revocation");
  const user = await prisma.user.findUniqueOrThrow({ where: { email } });
  const resetToken = randomBytes(32).toString("hex");
  await prisma.passwordReset.create({ data: { tokenHash: createHash("sha256").update(resetToken).digest("hex"), userId: user.id, expiresAt: new Date(Date.now() + 60000) } });
  assert.equal((await request("/api/auth/reset-password", { token: resetToken, password })).status, 200);
  assert.equal((await request("/api/auth/reset-password", { token: resetToken, password })).status, 400);
  assert.equal((await request("/api/cart", { padding: "x".repeat(70000) }, carts[0].cookie)).status, 413);
  for (let i = 0; i < 10; i++) await request("/api/auth/register", {});
  assert.equal((await request("/api/auth/register", {})).status, 429);
  console.log("PASS: one-use password reset, request size limit and rate limiting");
  await processEmailQueue();
  const job = await prisma.emailJob.findFirstOrThrow();
  assert.equal(job.status, "PENDING"); assert.equal(job.attempts, 1);
  await prisma.emailJob.update({ where: { id: job.id }, data: { attempts: 4, availableAt: new Date(0) } });
  await processEmailQueue();
  assert.equal((await prisma.emailJob.findUniqueOrThrow({ where: { id: job.id } })).status, "FAILED");
  console.log("PASS: missing SMTP retries and eventually exposes a failed delivery");
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => prisma.$disconnect());
